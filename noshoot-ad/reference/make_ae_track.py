#!/usr/bin/env python3
"""
Turn the solved screen track into things After Effects can eat directly.

Writes into Assets/To Be Edited/_track/:
  CornerPin_<comp>.txt   AE clipboard keyframe data - select a Corner Pin
                         effect's 4 point properties and paste. One file per
                         target comp resolution.
  screen_track.jsx       the track as a JSX include: a global array the build
                         script reads to key Corner Pin without any clipboard
                         step at all. This is the one the AE script uses.
  TRACK-NOTES.md         measured numbers + the exact AE settings they imply

The corner data is in MASTER pixel coords (3840x2160). AE's Corner Pin wants
LAYER coords, which are the same thing when the footage sits unscaled in a comp
of the same size. For a 1920x1080 comp holding the 4K plate scaled to 50%, the
numbers halve - handled by the `scale` argument per output.
"""
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
TRACK = HERE.parent / "Assets" / "To Be Edited" / "_track" / "screen_track.json"
OUT = TRACK.parent

FPS = 60.0
CORNERS = [("tl", "Upper Left"), ("tr", "Upper Right"),
           ("bl", "Lower Left"), ("br", "Lower Right")]


def ae_clipboard(track, scale, w, h):
    """
    AE keyframe-clipboard format. Pasting this onto a Corner Pin effect keys all
    four points across every frame - the same result as a Mocha solve, minus
    Mocha.
    """
    L = ["Adobe After Effects 8.0 Keyframe Data", "",
         f"\tUnits Per Second\t{FPS:.2f}",
         f"\tSource Width\t{w}", f"\tSource Height\t{h}",
         "\tSource Pixel Aspect Ratio\t1", "\tComp Pixel Aspect Ratio\t1", ""]
    for key, label in CORNERS:
        L.append(f"Effects\tCorner Pin #1\t{label} #2")
        L.append("\tFrame\tX pixels\tY pixels")
        for i, f in enumerate(track):
            x, y = f[key][0] * scale, f[key][1] * scale
            L.append(f"\t{i}\t{x:.3f}\t{y:.3f}")
        L.append("")
    L.append("End of Keyframe Data")
    return "\n".join(L)


def main():
    if not TRACK.exists():
        sys.exit("run track_screen.py then analyze_taps.py first")
    d = json.loads(TRACK.read_text())
    track = d["track"]
    mw, mh = d["master_res"]
    taps = d["taps"]
    col = d["screen_colour"]

    # 1. clipboard files at both working resolutions
    outputs = [
        ("4K_master", 1.0, mw, mh),          # plate at native 3840x2160
        ("1920x1080", 0.5, 1920, 1080),      # plate scaled 50% into an HD comp
    ]
    for name, sc, w, h in outputs:
        p = OUT / f"CornerPin_{name}.txt"
        p.write_text(ae_clipboard(track, sc, w, h))
        print(f"wrote {p.name}")

    # 2. JSX include - what the AE build script actually reads
    def arr(sc):
        rows = []
        for f in track:
            rows.append("[%.1f,%.1f,%.1f,%.1f,%.1f,%.1f,%.1f,%.1f]" % (
                f["tl"][0] * sc, f["tl"][1] * sc, f["tr"][0] * sc, f["tr"][1] * sc,
                f["br"][0] * sc, f["br"][1] * sc, f["bl"][0] * sc, f["bl"][1] * sc))
        return ",\n ".join(rows)

    jsx = [
        "// AUTO-GENERATED by Tools/make_ae_track.py - do not hand-edit.",
        "// Screen-corner track for Shot_07_09_OTS, solved from the green screen.",
        "// Each row = [tlx,tly, trx,try, brx,bry, blx,bly] for one frame @60fps.",
        "// SCREEN_TRACK_HD is in 1920x1080 comp coords (plate scaled to 50%).",
        "",
        f"var SCREEN_TRACK_FPS = {FPS};",
        f"var SCREEN_TRACK_FRAMES = {len(track)};",
        "var SCREEN_TAPS_SEC = [%s];" % ", ".join(
            "%.3f" % t["contact_sec"] for t in taps),
        "var SCREEN_GREEN = [%.4f, %.4f, %.4f];  // measured %s" % (
            col["normalised"][0], col["normalised"][1], col["normalised"][2],
            col["hex"]),
        "",
        "var SCREEN_TRACK_HD = [",
        " " + arr(0.5),
        "];",
    ]
    p = OUT / "screen_track.jsx"
    p.write_text("\n".join(jsx))
    print(f"wrote {p.name}  ({len(track)} frames)")

    # 3. human-readable notes
    mv = d["movement"]
    travel = max(max(v["x_range_px"], v["y_range_px"]) for v in mv.values())
    sw, sh = d["screen_px_at_frame0"]
    notes = f"""# OTS SCREEN TRACK — measured numbers
Auto-generated from Shot_07_09_OTS.mov by Tools/track_screen.py + analyze_taps.py.
Plate: {mw}x{mh} @ {FPS:.0f}fps, {d['frames']} frames, {len(d['dropout_frames'])} tracking dropouts.

## THE SCREEN
Size at frame 0: {sw:.0f} x {sh:.0f} px (master), aspect {d['screen_aspect']:.3f}.
Measured green: {col['hex']}  rgb{tuple(col['rgb'])}
  -> put this in Keylight's Screen Colour instead of eyedropping.

Total corner travel across the whole 8s take: {travel:.0f} px on {mw} wide
  = {travel / mw * 100:.1f}% of frame width. The phone is nearly locked.

## WHAT THAT MEANS FOR THE BUILD
- Mocha is not needed. A Corner Pin keyed from this track is a complete solve;
  the data is per-frame, independently solved, so it cannot drift.
- The PhoneUI comps are 1080x2340 (aspect 2.167). The real screen is
  {d['screen_aspect']:.3f}. Corner Pin stretches to fit, so the UI will be
  squeezed ~{abs(d['screen_aspect'] / (2340 / 1080) - 1) * 100:.0f}% vertically.
  Either accept it (invisible at this size) or rebuild the UI comps at
  1080x{round(1080 * d['screen_aspect'])} for a true match.

## THE TAPS (drive the UI animation from these)
Detected from thumb-tip height inside the screen quad — the thumb extends from
a resting ~0.32 up the screen to ~0.50 on each tap.
"""
    for i, t in enumerate(taps, 1):
        notes += (f"  tap {i}: frame {t['contact_frame']:3d}  "
                  f"{t['contact_sec']:5.2f}s   tip {t['tip_height']:.2f}\n")
    notes += f"""
Peak thumb coverage of the screen: {max(d['thumb_cover']) * 100:.0f}%.

## THUMB HANDLING — SAM2 IS NOT NEEDED
The thumb is skin against saturated green. Keylight removes the green and the
thumb survives automatically as foreground, because it was never keyed out.
The cut sheet's "SAM2 thumb matte if the thumb crosses" is insurance against a
problem this plate does not have — the thumb never crosses the screen centre,
peaking at {max(d['thumb_cover']) * 100:.0f}% coverage from the lower right.

Order in AE (per screen comp):
  1. plate
  2. PhoneUI comp, Corner Pin keyed from this track
  3. plate again on top, Keylight (Screen Colour {col['hex']}) — this layer
     supplies the thumb over the UI. Screen Matte: Clip Black ~8, Clip White ~92.

## FILES
  CornerPin_4K_master.txt   paste onto a Corner Pin in a 3840x2160 comp
  CornerPin_1920x1080.txt   paste onto a Corner Pin in an HD comp (plate at 50%)
  screen_track.jsx          read directly by AE-SCRIPT-OTS.jsx — no pasting
  track_overlay.mp4         visual QC: solved quad drawn on the plate
"""
    p = OUT / "TRACK-NOTES.md"
    p.write_text(notes)
    print(f"wrote {p.name}")
    print(f"\nphone travel: {travel:.0f}px of {mw} = {travel / mw * 100:.1f}% — near-locked")
    print(f"screen green: {col['hex']}")
    print(f"taps at: {', '.join('%.2fs' % t['contact_sec'] for t in taps)}")


if __name__ == "__main__":
    main()
